// Общие помощники для русского текста.

/** Буква, цифра или подчёркивание в любом алфавите. */
const WORD_CHAR = '[\\p{L}\\p{N}_]';

/**
 * Оборачивает шаблон регулярного выражения в границы слова, которые работают для кириллицы.
 * В JS `\b` и `\w` понимают только ASCII даже с флагом `u`, поэтому границы — через lookaround.
 * Итоговое выражение нужно собирать с флагом `u`.
 * @param {string} source
 */
export function wordPattern(source) {
    return `(?<!${WORD_CHAR})(?:${source})(?!${WORD_CHAR})`;
}
