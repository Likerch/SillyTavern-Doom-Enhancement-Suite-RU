/**
 * Ключ лорбука «слово начинается с одной из основ» — и не внутри тега <…> (теги сцены ST сканирует вместе с чатом).
 * @param {readonly string[]} stems
 */
export function stemsKey(stems) {
    return regexKey(`${WORD_START}(?:${stems.join('|')})${OUTSIDE_TAG}`);
}

