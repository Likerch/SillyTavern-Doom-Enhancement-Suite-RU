// Русские служебные пометки, которые DES понимает только по-английски.

import { wordPattern } from './text.js';

/**
 * Пометки «персонажа нет в сцене» в мыслях. Берём только однозначные мета-формулировки:
 * мысли пишутся от первого лица, поэтому «ушла» или «уехал» чаще про кого-то другого.
 */
const OFF_SCENE = new RegExp([
    'не\\s+(?:находится|присутствует)\\s+(?:в|на)\\s+(?:сцене|месте\\s+действия|локации)',
    '(?:не|нет)\\s+(?:в|на)\\s+(?:сцене|кадре)',
    'вне\\s+(?:сцены|кадра)',
    'за\\s+кадром',
    'отсутствует\\s+(?:в|на)\\s+(?:сцене|месте\\s+действия|локации)',
].map(wordPattern).join('|'), 'iu');

/** Пометка в скобках: «(отсутствует)», «[не присутствует]», «(за кадром, дома)». */
const OFF_SCENE_BRACKETED = /[([]\s*(?:не\s+присутствует|отсутствует|не\s+в\s+сцене|вне\s+сцены|за\s+кадром)(?![\p{L}\p{N}_])[^)\]]{0,40}[)\]]/iu;

/**
 * @param {unknown} text мысли персонажа
 * @returns {string|null} найденная пометка или `null`
 */
export function findRussianOffScene(text) {
    const value = String(text ?? '');
    const match = value.match(OFF_SCENE) ?? value.match(OFF_SCENE_BRACKETED);
    return match ? match[0] : null;
}

const NO_QUEST = new RegExp(`^(?:${[
    '(?:пока\\s+)?(?:нет|нету|отсутству(?:ет|ют))(?:\\s+(?:(?:активн|текущ|основн|главн)(?:ого|ых|ой|ей)\\s+)?(?:квест(?:а|ов)?|задани(?:я|й)|цел(?:и|ей)|мисси(?:и|й)))?',
    'ничего',
    'пусто',
    'никаких(?:\\s+(?:квестов|заданий))?',
    '[—–-]+',
].join('|')})$`, 'iu');

/**
 * Модель написала «квеста нет» по-русски («Нет», «Отсутствует», «Нет активного квеста», «—»)?
 * @param {unknown} text название квеста
 */
export function isRussianNoQuest(text) {
    const value = String(text ?? '').trim().replace(/[.!…]+$/u, '').trim();
    return value.length > 0 && NO_QUEST.test(value);
}
