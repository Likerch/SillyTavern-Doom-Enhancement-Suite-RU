/** Уменьшительная форма → полные имена, к которым она относится. */
export const FULL_NAMES_BY_DIMINUTIVE = (() => {
    /** @type {Map<string, string[]>} */
    const map = new Map();
    for (const [full, forms] of Object.entries(DIMINUTIVES)) {
        for (const form of new Set(forms)) map.set(form, [...(map.get(form) ?? []), full]);
    }
    return map;
})();
